import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import ff from 'ffmpeg-static';
import probe from 'ffprobe-static';
const home=path.resolve(process.env.NOVA_HOME||'');
assert.ok(home.toLowerCase().includes('quality-review'),'explicit isolated quality-review NOVA_HOME required');
fs.mkdirSync(home,{recursive:true});process.env.TEMP=home;process.env.TMP=home;
const {renderAll}=await import('../src/pipeline/render.js');
test('production editorial branch preserves narration length and persists actual composition and sound events',async()=>{
 const dir=fs.mkdtempSync(path.join(home,'editorial-render-')),picture=path.join(dir,'source.png'),audio=path.join(dir,'voice.wav');
 execFileSync(ff,['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=s=640x360','-frames:v','1','-y',picture]);
 execFileSync(ff,['-hide_banner','-loglevel','error','-f','lavfi','-i','sine=frequency=200:duration=2','-y',audio]);
 const texts=['A question about the Moon.','The study began in 1969.','Evidence answers the question.'];
 const script={title:'Why Does the Evidence Remain?',sections:[{title:'Original study',segments:texts.map(text=>({text,visuals:[{query:'Original local test pattern',type:'image',kind:'generic'}]}))}]};
 const tts=texts.map((text,i)=>({segId:`s${i}`,audio,duration:2,words:text.split(' ').map((t,j)=>({t,start:j*.25,end:j*.25+.2}))}));
 const media=Object.fromEntries(texts.map((_,i)=>[`s${i}b0`,{type:'image',file:picture,provider:'original fixture'}]));
 const result=await renderAll({id:'editorial-real-test',theme:'belgesel',visualStyle:'editorial',language:'en',demo:true,subtitleMode:'classic',transitions:'yok',musicVolume:0,soundDesign:true,settingsSnapshot:{preset:'ultrafast',crf:28,fps:15,concurrency:1,cinemaGrade:false}},script,media,tts,dir,()=>{},()=>{},{cancelled:false,add(){},remove(){},delete(){}});
 const edit=JSON.parse(fs.readFileSync(path.join(dir,'edit-plan.json'))),sound=JSON.parse(fs.readFileSync(path.join(dir,'sound-plan.json')));
 assert.deepEqual(edit.scenes.map(s=>s.composition.layout),['opener','immersive','immersive']);
 assert.ok(edit.scenes.every(s=>s.composition.version===6&&s.composition.mediaRect.width===1920));
 assert.equal(sound.music.enabled,false);assert.ok(sound.cues.some(c=>c.kind.startsWith('editorial-')));
 assert.ok(!result.qualityWarnings.some(w=>w.includes('editoryal sahnesinde')));
 const data=JSON.parse(execFileSync(probe.path,['-v','error','-show_format','-show_streams','-of','json',path.join(dir,'output.mp4')],{encoding:'utf8'}));
 assert.ok(Math.abs(Number(data.format.duration)-result.durationSec)<.1);
 assert.ok(fs.readFileSync(path.join(dir,'subs.ass'),'utf8').includes('Classic,Segoe UI'));
 console.log(JSON.stringify({dir,duration:data.format.duration,layouts:edit.scenes.map(s=>s.composition.layout)}));
});
