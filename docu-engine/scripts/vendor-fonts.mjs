// Vendors the engine's fonts into public/fonts (woff2 + licences) and writes
// src/fontManifest.ts. Renders then load type from the job's own public dir
// (staticFile), never from Google Fonts: a flaky connection used to kill a
// render on "Fetching Inter font ... not cleared after 58000ms".
//
//   node scripts/vendor-fonts.mjs        (needs the network once; @remotion/google-fonts as a devDependency)
//
// FACES below is the complete set the engine loads (src/fonts.ts, src/looks/fonts.ts,
// src/devices/type.ts). Add a face here, re-run, commit public/fonts + src/fontManifest.ts.
import { createHash } from 'node:crypto';
import { mkdirSync, rmSync, writeFileSync, renameSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ENGINE = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ENGINE, 'public', 'fonts');
const require = createRequire(import.meta.url);

const LS = ['latin', 'latin-ext'];
// [import name, style, weights, subsets, licence path in github.com/google/fonts]
const FACES = [
  ['Anton', 'normal', ['400'], LS, 'ofl/anton/OFL.txt'],
  ['Inter', 'normal', ['400', '600', '800'], LS, 'ofl/inter/OFL.txt'],
  ['Oswald', 'normal', ['500', '700'], [...LS, 'cyrillic'], 'ofl/oswald/OFL.txt'],
  ['IBMPlexMono', 'normal', ['400', '600'], LS, 'ofl/ibmplexmono/OFL.txt'],
  ['Cinzel', 'normal', ['600', '800'], LS, 'ofl/cinzel/OFL.txt'],
  ['CrimsonPro', 'normal', ['400', '600'], LS, 'ofl/crimsonpro/OFL.txt'],
  ['CrimsonPro', 'italic', ['400', '600'], LS, null],
  ['BebasNeue', 'normal', ['400'], LS, 'ofl/bebasneue/OFL.txt'],
  ['CourierPrime', 'normal', ['400', '700'], LS, 'ofl/courierprime/OFL.txt'],
  ['Exo2', 'normal', ['400', '700', '800'], LS, 'ofl/exo2/OFL.txt'],
  ['PlayfairDisplay', 'normal', ['600', '800'], LS, 'ofl/playfairdisplay/OFL.txt'],
  ['PlayfairDisplay', 'italic', ['500', '700'], LS, null],
  ['Lora', 'normal', ['400', '600'], LS, 'ofl/lora/OFL.txt'],
  ['OldStandardTT', 'normal', ['400', '700'], [...LS, 'cyrillic'], 'ofl/oldstandardtt/OFL.txt'],
  ['UnifrakturMaguntia', 'normal', ['400'], ['latin'], 'ofl/unifrakturmaguntia/OFL.txt'],
  ['DMSerifDisplay', 'normal', ['400'], LS, 'ofl/dmserifdisplay/OFL.txt'],
  ['DMSerifDisplay', 'italic', ['400'], LS, null],
  ['SpaceGrotesk', 'normal', ['400', '500', '700'], LS, 'ofl/spacegrotesk/OFL.txt'],
  ['ArchivoBlack', 'normal', ['400'], LS, 'ofl/archivoblack/OFL.txt'],
  ['JetBrainsMono', 'normal', ['400', '700'], LS, 'ofl/jetbrainsmono/OFL.txt'],
  ['Caveat', 'normal', ['500', '700'], LS, 'ofl/caveat/OFL.txt'],
  ['SpecialElite', 'normal', ['400'], LS, 'apache/specialelite/LICENSE.txt'],
];

async function get(url) {
  for (let k = 0; ; k++) {
    try {
      const r = await fetch(url);
      if (!r.ok) throw new Error(`${r.status} ${url}`);
      return Buffer.from(await r.arrayBuffer());
    } catch (e) {
      if (k >= 3) throw e;
      await new Promise((ok) => setTimeout(ok, 1000 * (k + 1)));
    }
  }
}

const tmp = `${OUT}.new`;
rmSync(tmp, { recursive: true, force: true });
mkdirSync(join(tmp, 'licenses'), { recursive: true });

/** family -> style -> weight -> subset -> [file, unicodeRange] */
const manifest = {};
const byUrl = new Map();
for (const [name, style, weights, subsets, licence] of FACES) {
  const info = require(`@remotion/google-fonts/${name}`).getInfo();
  const fam = (manifest[info.fontFamily] ??= {});
  for (const w of weights) {
    for (const s of subsets) {
      const url = info.fonts?.[style]?.[w]?.[s];
      if (!url) throw new Error(`${name} ${style} ${w} ${s}: not on Google Fonts`);
      let file = byUrl.get(url);
      if (!file) {
        // Variable families serve one file for several weights: stored once.
        file = `${name}-${style}-${s}-${createHash('sha1').update(url).digest('hex').slice(0, 8)}.woff2`;
        writeFileSync(join(tmp, file), await get(url));
        byUrl.set(url, file);
        console.log('›', file);
      }
      ((fam[style] ??= {})[w] ??= {})[s] = [file, info.unicodeRanges[s]];
    }
  }
  if (licence) {
    const text = await get(`https://raw.githubusercontent.com/google/fonts/main/${licence}`);
    writeFileSync(join(tmp, 'licenses', `${name}-${licence.split('/').pop()}`), text);
  }
}
writeFileSync(
  join(tmp, 'licenses', 'README.txt'),
  'Fonts in this folder are redistributed unmodified from Google Fonts (fonts.gstatic.com woff2 subsets).\n' +
    'Each family is under the SIL Open Font License 1.1 (OFL.txt) except Special Elite (Apache License 2.0).\n',
);
rmSync(OUT, { recursive: true, force: true });
renameSync(tmp, OUT);

const ts =
  '// GENERATED by scripts/vendor-fonts.mjs: do not edit. The engine\'s vendored fonts (public/fonts).\n' +
  '// family -> style -> weight -> subset -> [file in public/fonts, CSS unicode-range]\n' +
  `export const FONT_FILES: Record<string, Record<string, Record<string, Record<string, readonly [string, string]>>>> = ${JSON.stringify(manifest, null, 2)};\n`;
const mf = join(ENGINE, 'src', 'fontManifest.ts');
writeFileSync(`${mf}.tmp`, ts);
renameSync(`${mf}.tmp`, mf);
console.log(`${byUrl.size} files, ${Object.keys(manifest).length} families -> public/fonts, src/fontManifest.ts`);
